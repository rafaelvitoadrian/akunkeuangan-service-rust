-- PostgreSQL only. SQLx executes this migration in a transaction under its
-- migration advisory lock. Never change applied migrations; add a new version.
CREATE TABLE IF NOT EXISTS activationtype (
    ident_activationtype BIGINT PRIMARY KEY,
    typename TEXT NOT NULL
);
CREATE TABLE IF NOT EXISTS revisionstate (
    ident_revisionstate BIGINT PRIMARY KEY,
    name TEXT NOT NULL
);
INSERT INTO activationtype VALUES
    (1, 'Active'), (2, 'Deactivated'), (4, 'Suspended'), (5, 'Inactive')
    ON CONFLICT DO NOTHING;
INSERT INTO revisionstate VALUES
    (1, 'Ready'), (2, 'AwaitingApproval'), (3, 'ValidationFailed'),
    (4, 'Rejected'), (5, 'Draft'), (6, 'Deleted'), (7, 'Error'), (8, 'Pending')
    ON CONFLICT DO NOTHING;

CREATE TABLE IF NOT EXISTS systemprop (
    propname TEXT PRIMARY KEY,
    propvalue TEXT
);
-- Production JWT key generation remains enabled on a new database.
INSERT INTO systemprop VALUES ('is.test', 'false') ON CONFLICT DO NOTHING;

CREATE SEQUENCE IF NOT EXISTS users_sequence;
CREATE SEQUENCE IF NOT EXISTS seq_account_composite;
CREATE SEQUENCE IF NOT EXISTS category_sequence;
CREATE SEQUENCE IF NOT EXISTS transaksikeuangan_sequence;

CREATE TABLE IF NOT EXISTS users (
    id BIGINT PRIMARY KEY DEFAULT nextval('users_sequence'),
    name TEXT,
    email TEXT,
    username TEXT,
    pwd TEXT,
    password TEXT,
    salt TEXT,
    createddate TIMESTAMP,
    updateddate TIMESTAMP,
    ident_master BIGINT REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
    ident_revision BIGINT REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
    revision_effective_from TIMESTAMP,
    revision_effective_to TIMESTAMP,
    requested_activation_date DATE,
    ident_activationtype BIGINT REFERENCES activationtype,
    ident_lastupdateuser BIGINT REFERENCES users(id) DEFERRABLE INITIALLY DEFERRED,
    lastupdatetime TIMESTAMP,
    ident_revisionstate BIGINT REFERENCES revisionstate
);
CREATE INDEX IF NOT EXISTS users_email_master_idx ON users(email) WHERE ident_master IS NULL;
CREATE INDEX IF NOT EXISTS users_master_idx ON users(ident_master);

CREATE TABLE IF NOT EXISTS akunkeuangan (
    id BIGINT PRIMARY KEY DEFAULT nextval('seq_account_composite'),
    name TEXT,
    description TEXT,
    id_user BIGINT REFERENCES users(id),
    saldo NUMERIC,
    account_number TEXT,
    createddate TIMESTAMP,
    updateddate TIMESTAMP,
    ident_master BIGINT REFERENCES akunkeuangan(id) DEFERRABLE INITIALLY DEFERRED,
    ident_revision BIGINT REFERENCES akunkeuangan(id) DEFERRABLE INITIALLY DEFERRED,
    revision_effective_from TIMESTAMP,
    revision_effective_to TIMESTAMP,
    requested_activation_date DATE,
    ident_activationtype BIGINT REFERENCES activationtype,
    ident_lastupdateuser BIGINT REFERENCES users(id),
    lastupdatetime TIMESTAMP,
    ident_revisionstate BIGINT REFERENCES revisionstate
);
CREATE INDEX IF NOT EXISTS akunkeuangan_user_idx ON akunkeuangan(id_user) WHERE ident_master IS NULL;
CREATE INDEX IF NOT EXISTS akunkeuangan_master_idx ON akunkeuangan(ident_master);

CREATE TABLE IF NOT EXISTS category (
    id BIGINT PRIMARY KEY DEFAULT nextval('category_sequence'),
    category_name TEXT,
    category_type NUMERIC,
    id_akuntransaksi BIGINT REFERENCES akunkeuangan(id),
    createddate TIMESTAMP,
    updateddate TIMESTAMP
);
CREATE INDEX IF NOT EXISTS category_account_idx ON category(id_akuntransaksi, createddate DESC);

CREATE TABLE IF NOT EXISTS transaksikeuangan (
    id BIGINT PRIMARY KEY DEFAULT nextval('transaksikeuangan_sequence'),
    name TEXT,
    description TEXT,
    id_akuntransaksi BIGINT REFERENCES akunkeuangan(id),
    category_id BIGINT REFERENCES category(id),
    jenis NUMERIC,
    nominal NUMERIC,
    createddate TIMESTAMP,
    updateddate TIMESTAMP,
    transaksi_date TIMESTAMP,
    externalreference TEXT,
    internalreference TEXT
);
CREATE INDEX IF NOT EXISTS transaksi_account_idx ON transaksikeuangan(id_akuntransaksi, transaksi_date DESC);

-- Read compatibility only; JMS, settlement processing and audit writes remain
-- deferred. These tables do not start any integration or background worker.
CREATE TABLE IF NOT EXISTS csv_settlementinstruction_akunkeuangan (
    instructionreference TEXT PRIMARY KEY
);
CREATE TABLE IF NOT EXISTS auditevententry (
    ident_auditevententry BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    eventid TEXT,
    entryname TEXT,
    entrytimestamp TIMESTAMP,
    NANOSECONDSONTIMESTAMP INTEGER,
    businessidentifier TEXT,
    entrydata TEXT,
    compressedentrydata BYTEA,
    entityname TEXT,
    entityid BIGINT,
    masterid BIGINT,
    revisionid BIGINT
);
CREATE INDEX IF NOT EXISTS audit_event_idx ON auditevententry(eventid, ident_auditevententry);
