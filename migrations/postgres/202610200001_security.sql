-- PostgreSQL only. Additive migration; no implicit grants to existing users.
CREATE TABLE authlevel (
    id BIGINT PRIMARY KEY, name TEXT NOT NULL
);
CREATE TABLE accesslevel (
    id BIGINT PRIMARY KEY, name TEXT NOT NULL
);
INSERT INTO authlevel VALUES (1, 'None'), (2, 'Single'), (3, 'Double');
INSERT INTO accesslevel VALUES (2, 'View'), (3, 'Initiate'), (4, 'Approve');
CREATE TABLE security_function (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    function_name TEXT NOT NULL UNIQUE,
    authlevel_id BIGINT REFERENCES authlevel,
    description TEXT
);
-- The service currently guards UserAccount VIEW/APPROVE. Other operations
-- can be registered explicitly without changing the API contract.
INSERT INTO security_function(function_name, authlevel_id, description)
    VALUES ('UserAccount', 2, 'User account administration');
CREATE TABLE userrole (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shortname TEXT NOT NULL,
    name TEXT NOT NULL,
    description TEXT,
    activation_status TEXT NOT NULL CHECK (activation_status IN ('Active','Suspended','Deactivated')),
    last_update TIMESTAMP NOT NULL,
    applicable_for_poa BOOLEAN NOT NULL DEFAULT FALSE,
    internal BOOLEAN NOT NULL DEFAULT FALSE,
    last_update_user BIGINT REFERENCES users(id)
);
CREATE UNIQUE INDEX userrole_shortname_unique ON userrole(upper(shortname)) WHERE NOT internal;
CREATE TABLE userrolefunction (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    role_id BIGINT NOT NULL REFERENCES userrole ON DELETE CASCADE,
    function_id BIGINT NOT NULL REFERENCES security_function,
    accesslevel_id BIGINT NOT NULL REFERENCES accesslevel,
    UNIQUE(role_id, function_id)
);
CREATE TABLE permissionprofile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name TEXT,
    user_id BIGINT REFERENCES users(id),
    deactivation_date DATE
);
CREATE TABLE permissionprofile_userrole (
    profile_id BIGINT NOT NULL REFERENCES permissionprofile ON DELETE CASCADE,
    role_id BIGINT NOT NULL REFERENCES userrole,
    PRIMARY KEY(profile_id, role_id)
);
CREATE TABLE useraccountpermissionprofile (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    profile_id BIGINT NOT NULL REFERENCES permissionprofile,
    PRIMARY KEY(user_id, profile_id)
);
CREATE INDEX useraccountpermissionprofile_profile_idx ON useraccountpermissionprofile(profile_id);
